#!/usr/bin/env python3
"""TM-25: turn a production v3 message into a scripted test (tests/agent_api/replays/).

    python3 scripts/replay_to_test.py cor_a838368708e5476aa92a8224e25b9038 [--name short-slug]
    python3 scripts/replay_to_test.py --from-json turn.json --name short-slug     (no production access)

Reads the message's ``agent_api_turn`` trace (words, tool calls with arguments, API answers) through the
read-only control plane (scripts/control_plane.py, MESIRI_CLAUDE_OPS_TOKEN) and writes a test that replays
that turn through ApiAgent (tests/agent_api/replaykit.py). The test records what happened; edit its
expectations to what should happen, so it fails before the fix. Customer words end up in the test: keep
names and numbers out (the script masks phone-like digit runs of 8 or more), and refer to the person by role.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps" / "whatsapp-assistant" / "tests" / "agent_api" / "replays"
_ID = re.compile(r"^cor_[0-9a-f]{8,40}$")


def _mask(value):
    if isinstance(value, str):
        # Phone-like numbers only: a run of 8+ digits not inside an id (UUID / hex), which must stay usable.
        return re.sub(r"(?<![\w-])\d{8,}(?![\w-])", lambda m: "x" * len(m.group()), value)
    if isinstance(value, list):
        return [_mask(v) for v in value]
    if isinstance(value, dict):
        return {k: _mask(v) for k, v in value.items()}
    return value


def fetch(correlation_id: str) -> dict:
    sql = ("SELECT t.stage_payload::text AS payload, left(m.assistant_reply, 2000) AS reply, "
           "to_char(m.received_at, 'YYYY-MM-DD') AS day FROM journey_traces t "
           "JOIN inbound_messages m ON m.correlation_id = t.correlation_id "
           f"WHERE t.correlation_id = '{correlation_id}' AND t.stage = 'agent_api_turn' "
           "ORDER BY t.created_at DESC LIMIT 1")
    out = subprocess.run([sys.executable, str(ROOT / "scripts" / "control_plane.py"), "sql", sql, "--json"],
                         capture_output=True, text=True, check=False)
    if out.returncode != 0:
        sys.exit(f"control plane: {out.stderr.strip() or out.stdout.strip()}")
    data = json.loads(out.stdout)
    rows = data.get("rows") or []
    if not rows:
        sys.exit(f"no v3 turn traced for {correlation_id}")
    cols = data.get("columns") or ["payload", "reply", "day"]
    row = dict(zip(cols, rows[0], strict=False)) if isinstance(rows[0], list) else rows[0]
    payload = json.loads(row["payload"]) if isinstance(row["payload"], str) else row["payload"]
    return {**payload, "reply": row.get("reply") or "", "day": row.get("day"), "correlation_id": correlation_id}


def render(recorded: dict, name: str) -> str:
    recorded = _mask({k: recorded.get(k) for k in ("correlation_id", "day", "text", "facts", "calls", "reply", "pending", "asked")})
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "turn"
    tools = [c.get("tool") for c in recorded.get("calls") or []]
    pending = recorded.get("pending") or []
    return f'''"""Replay of a production v3 turn ({recorded.get("day") or "?"}, {recorded.get("correlation_id") or "recorded"}).

Generated by scripts/replay_to_test.py (TM-25, WA-148). Two tests:
- scripted: the same tool calls again; asserts what HAPPENED, so the code around the model stays the same;
- live (-m live, the "SOP eval" workflow): the real model reads today's SOP.md on the same words and API
  answers, and must do what EXPECT says. Edit EXPECT to what SHOULD happen: it fails before the fix.
"""

from __future__ import annotations

import pytest
from tests.agent_api.replaykit import check, load, replay

RECORDED = load(r"""{json.dumps(recorded, ensure_ascii=False, indent=1)}""")

#: What the real model must do with these words (edit: this is the spec of the fix).
EXPECT = {{
    "must_call": {sorted(set(t for t in tools if t))!r},
    "must_not_call": [],
    "pending": {pending!r},
}}


async def test_replay_{slug}() -> None:
    turn, _api = await replay(RECORDED)
    # What happened in production (scripted: the same calls again).
    assert [c["tool"] for c in turn.calls] == {tools!r}
    assert [e.summary for e in turn.pending] == {pending!r}


@pytest.mark.live
async def test_replay_{slug}_live() -> None:
    turn, _api = await replay(RECORDED, live=True)
    assert check(turn, EXPECT) == []
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("correlation_id", nargs="?")
    parser.add_argument("--from-json", type=Path)
    parser.add_argument("--name", default="")
    args = parser.parse_args()
    if args.from_json:
        recorded = json.loads(args.from_json.read_text(encoding="utf-8"))
    elif args.correlation_id and _ID.match(args.correlation_id):
        recorded = fetch(args.correlation_id)
    else:
        parser.error("give a correlation id (cor_...) or --from-json")
    name = args.name or (recorded.get("correlation_id") or "turn")[4:12]
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"test_replay_{re.sub(r'[^a-z0-9]+', '_', name.lower()).strip('_')}.py"
    path.write_text(render(recorded, name), encoding="utf-8")
    print(path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
