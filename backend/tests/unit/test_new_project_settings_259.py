"""[259] (5 Nov, a new customer): a project created on WhatsApp right after sign-up got UTC and no daily
report, while the sign-up project had the company's zone and the report on. In production every one of the
8 projects created after sign-up was like that, from the dashboard too. A new project now takes the
company's settings; what the caller sets still wins."""

from __future__ import annotations

import uuid
from types import SimpleNamespace
from typing import Any

import pytest

from mesiri.application.projects.defaults import FALLBACK_ZONE, ReportSettings, new_project_settings
from mesiri.domains.projects import router as projects

ORG = uuid.uuid4()


class Conn:
    """Answers the two reads (the company's reporting project, the company's zone) and keeps inserts."""

    def __init__(self, project: dict[str, Any] | None, zone: str | None, existing: list | None = None) -> None:
        self.project, self.zone, self.existing = project, zone, existing or []
        self.inserted: dict[str, Any] = {}

    async def execute(self, statement: Any, params: Any = None) -> Any:  # noqa: ANN401
        if getattr(statement, "is_insert", False):
            self.inserted = dict(statement.compile().params)
            return SimpleNamespace()
        sql = str(statement)
        if "FROM organizations" in sql:
            return SimpleNamespace(scalar=lambda: self.zone)
        if "auto_generate_dpr DESC" in sql:
            return SimpleNamespace(mappings=lambda: SimpleNamespace(first=lambda: self.project))
        return SimpleNamespace(fetchall=lambda: self.existing, first=lambda: None)


def _project(zone: str, on: bool, cutoff: str = "18:00", deadline: str = "21:00") -> dict[str, Any]:
    return {"reporting_timezone": zone, "auto_generate_dpr": on, "reporting_cutoff_time": cutoff,
            "dpr_send_deadline": deadline}


async def test_the_reported_case_gets_the_company_zone_and_the_report() -> None:
    # "We are rolla builders": sign-up project Asia/Kolkata + report on; the WhatsApp project got UTC / off.
    settings = await new_project_settings(Conn(_project("Asia/Kolkata", True), "Asia/Kolkata"), ORG)
    assert settings == ReportSettings("Asia/Kolkata", True, "18:00", "21:00")


async def test_old_utc_projects_are_not_copied() -> None:
    # The test company's newest projects were all UTC / off by default; its report project is copied instead.
    conn = Conn(_project("Asia/Kolkata", True, "19:00", "21:30"), "Asia/Kolkata")
    assert await new_project_settings(conn, ORG) == ReportSettings("Asia/Kolkata", True, "19:00", "21:30")
    # A report project left on UTC (never chosen) takes the company's zone.
    conn = Conn(_project("UTC", True), "Asia/Kolkata")
    assert (await new_project_settings(conn, ORG)).reporting_timezone == "Asia/Kolkata"


async def test_a_company_whose_projects_all_have_the_report_off_keeps_it_off() -> None:
    settings = await new_project_settings(Conn(_project("UTC", False), "Asia/Dubai"), ORG)
    assert settings.auto_generate_dpr is False and settings.reporting_timezone == "Asia/Dubai"


async def test_the_first_project_is_as_sign_up_sets_it() -> None:
    assert await new_project_settings(Conn(None, "Asia/Dubai"), ORG) == ReportSettings(
        "Asia/Dubai", True, "18:00", "21:00")
    assert (await new_project_settings(Conn(None, None), ORG)).reporting_timezone == FALLBACK_ZONE
    assert (await new_project_settings(Conn(None, "India"), ORG)).reporting_timezone == FALLBACK_ZONE


async def test_post_projects_stores_the_company_settings_when_left_out() -> None:
    conn = Conn(_project("Asia/Kolkata", True), "Asia/Kolkata")
    made = await projects.create_project(projects.ProjectCreate(name="Supermarket Kerala"), {"org": str(ORG)}, conn)
    assert conn.inserted["reporting_timezone"] == "Asia/Kolkata" and conn.inserted["auto_generate_dpr"] is True
    assert made.reportingTimezone == "Asia/Kolkata" and made.autoGenerateDpr is True


@pytest.mark.parametrize("auto", [True, False])
async def test_what_the_caller_sets_still_wins(auto: bool) -> None:
    conn = Conn(_project("Asia/Kolkata", not auto), "Asia/Kolkata")
    body = projects.ProjectCreate(name="Tower C", reportingTimezone="Asia/Dubai", autoGenerateDpr=auto,
                                  reportingCutoffTime="17:00", dprSendDeadline="20:00")
    made = await projects.create_project(body, {"org": str(ORG)}, conn)
    assert conn.inserted["reporting_timezone"] == "Asia/Dubai" and conn.inserted["auto_generate_dpr"] is auto
    assert conn.inserted["reporting_cutoff_time"] == "17:00" and made.dprSendDeadline == "20:00"
