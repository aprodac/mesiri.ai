@router.get("/{project_id}/members", response_model=list[ProjectMemberResponse])
async def list_project_members(
    project_id: uuid.UUID,
    auth_context: AuthorizationContext = Depends(get_auth_context),
    conn: AsyncConnection = Depends(get_db_conn),
):
    proj_result = await conn.execute(
        sa.select(_projects.c.id).where(
            _projects.c.id == project_id,
            _projects.c.organization_id == auth_context.organization_id,
        )
    )
    if proj_result.first() is None:
        raise HTTPException(status_code=404, detail="Project not found")

    query = (
        sa.select(
            _project_members.c.user_id,
            _project_members.c.role.label("member_role"),
            sa.text("u.email"),
            sa.text("u.full_name"),
            sa.text("u.status"),
        )
        .select_from(
            _project_members.join(
                sa.text("users u"),
                _project_members.c.user_id == sa.text("u.id"),
            )
        )
        .where(_project_members.c.project_id == project_id)
    )
    result = await conn.execute(query)
    return [
        ProjectMemberResponse(
            userId=r.user_id,
            email=r.email,
            fullName=r.full_name,
            role=r.member_role,
            status=r.status,
        )
        for r in result.fetchall()
    ]


@router.post("/{project_id}/members", response_model=ProjectMemberResponse, status_code=201)
async def add_project_member(
    project_id: uuid.UUID,
    body: ProjectMemberAdd,
    auth_context: AuthorizationContext = Depends(get_auth_context),
    conn: AsyncConnection = Depends(get_db_conn),
):
    if auth_context.role.upper() != "ADMIN":
        raise HTTPException(status_code=403, detail="Admin access required to add member")

    proj_result = await conn.execute(
        sa.select(_projects.c.id).where(
            _projects.c.id == project_id,
            _projects.c.organization_id == auth_context.organization_id,
        )
    )
    if proj_result.first() is None:
        raise HTTPException(status_code=404, detail="Project not found")

    user_result = await conn.execute(
        sa.select(sa.text("id, email, full_name, status")).where(
            sa.text("id = :user_id AND organization_id = :org_id")
        ),
        {"user_id": body.userId, "org_id": auth_context.organization_id},
    )
    user_row = user_result.first()
    if user_row is None:
        raise HTTPException(status_code=404, detail="User not found in organization")

    try:
        member_id = uuid.uuid4()
        await conn.execute(
            _project_members.insert().values(
                id=member_id,
                project_id=project_id,
                user_id=body.userId,
                role=body.role,
            )
        )
    except Exception as e:
        if "unique" in str(e).lower() or "23505" in str(e):
            raise HTTPException(
                status_code=409, detail="User is already a member of this project"
            ) from e
        raise

    return ProjectMemberResponse(
        userId=user_row.id,
        email=user_row.email,
        fullName=user_row.full_name,
        role=body.role,
        status=user_row.status,
    )


