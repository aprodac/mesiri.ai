def _valid_send_deadline(value: str) -> str:
    """"HH:MM" (BE-16): the time the project DPR goes out at the latest."""
    from mesiri.application.automations.scheduling import parse_time_of_day

    try:
        parsed = parse_time_of_day(value)
    except (ValueError, IndexError):
        raise HTTPException(status_code=422, detail="dprSendDeadline must be HH:MM") from None
    return parsed.strftime("%H:%M")


