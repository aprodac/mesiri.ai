def _iana_zone(value: str | None) -> str | None:
    """DSH-03: a project's time zone is an IANA name. "IST" or "India" used
    to be saved and then quietly read as UTC when the evening check ran."""
    if value is None:
        return None
    try:
        ZoneInfo(value)
    except (ZoneInfoNotFoundError, ValueError, OSError) as exc:
        raise ValueError(
            f'"{value}" is not a time zone. Pick one from the list, e.g. Asia/Kolkata.'
        ) from exc
    return value


