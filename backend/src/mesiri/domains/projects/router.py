@router.get("", response_model=list[ProjectResponse])
async def list_projects(
    auth_context: AuthorizationContext = Depends(get_auth_context),
    conn: AsyncConnection = Depends(get_db_conn),
):
    """List all projects accessible to the authenticated user."""
    # Create repository and handler
    repository = PostgresProjectRepository(conn)
    handler = ListProjectsHandler(repository)

    # Execute query
    query = ListProjects()
    projects = await handler.handle(query, auth_context)

    # Transform to HTTP response
    return ProjectPresenter.to_response_list(projects)


@router.post("", response_model=ProjectResponse, status_code=201)
async def create_project(
    body: ProjectCreate,
    admin: dict = Depends(require_admin),
    conn: AsyncConnection = Depends(get_db_conn),
):
    org_id = admin.get("org")
    project_id = uuid.uuid4()
    await conn.execute(
        _projects.insert().values(
            id=project_id,
            organization_id=org_id,
            name=body.name,
            code=body.code,
            location=body.location,
            client=body.client,
            description=body.description,
            reporting_timezone=body.reportingTimezone,
            reporting_cutoff_time=body.reportingCutoffTime,
            auto_generate_dpr=body.autoGenerateDpr,
            dpr_send_deadline=_valid_send_deadline(body.dprSendDeadline),
            required_report_types=body.requiredReportTypes,
        )
    )
    return ProjectResponse(
        id=project_id,
        name=body.name,
        code=body.code,
        location=body.location,
        client=body.client,
        description=body.description,
        status="success",
        statusLabel="On Track",
        progress=0,
        openIssues=0,
        reportingRatio=None,
        reportingTimezone=body.reportingTimezone,
        reportingCutoffTime=body.reportingCutoffTime,
        autoGenerateDpr=body.autoGenerateDpr,
        dprSendDeadline=_valid_send_deadline(body.dprSendDeadline),
        requiredReportTypes=body.requiredReportTypes,
    )


@router.get("/{project_id}", response_model=ProjectResponse)
async def get_project(
    project_id: uuid.UUID,
    auth_context: AuthorizationContext = Depends(get_auth_context),
    conn: AsyncConnection = Depends(get_db_conn),
):
    query = sa.select(_projects).where(
        _projects.c.id == project_id,
        _projects.c.organization_id == auth_context.organization_id,
    )
    result = await conn.execute(query)
    row = result.first()
    if row is None:
        raise HTTPException(status_code=404, detail="Project not found")

    # Check project scope permissions
    if not auth_context.project_scope.grants_all_org_projects:
        if project_id not in auth_context.project_scope.project_ids:
            raise HTTPException(status_code=403, detail="Access denied to this project")

    from mesiri.application.projects.dtos import ProjectDTO

    dto = ProjectDTO(
        id=row.id,
        organization_id=row.organization_id,
        name=row.name,
        code=row.code,
        location=row.location,
        client=row.client,
        description=row.description,
        status=row.status or "on_track",
        progress=row.progress or 0,
        open_issues=row.open_issues or 0,
        reporting_timezone=row.reporting_timezone or "UTC",
        reporting_cutoff_time=row.reporting_cutoff_time or "18:00",
        auto_generate_dpr=bool(row.auto_generate_dpr),
        dpr_send_deadline=row.dpr_send_deadline or "21:00",
        required_report_types=row.required_report_types or None,
    )
    return ProjectPresenter.to_response(dto)


@router.put("/{project_id}", response_model=ProjectResponse)
async def update_project(
    project_id: uuid.UUID,
    body: ProjectUpdate,
    auth_context: AuthorizationContext = Depends(get_auth_context),
    conn: AsyncConnection = Depends(get_db_conn),
):
    if auth_context.role.upper() != "ADMIN":
        raise HTTPException(status_code=403, detail="Admin access required to edit project")

    query = sa.select(_projects).where(
        _projects.c.id == project_id,
        _projects.c.organization_id == auth_context.organization_id,
    )
    result = await conn.execute(query)
    row = result.first()
    if row is None:
        raise HTTPException(status_code=404, detail="Project not found")

    values = {}
    if body.name is not None:
        values["name"] = body.name
    if body.code is not None:
        values["code"] = body.code
    if body.location is not None:
        values["location"] = body.location
    if body.client is not None:
        values["client"] = body.client
    if body.description is not None:
        values["description"] = body.description
    if body.status is not None:
        status_map = {
            "success": "on_track",
            "warning": "at_risk",
            "critical": "critical",
            "neutral": "on_hold",
            "active": "on_track",
            "on_track": "on_track",
            "at_risk": "at_risk",
            "on_hold": "on_hold",
            "completed": "completed",
            "archived": "archived",
        }
        values["status"] = status_map.get(body.status, body.status)
    if body.reportingTimezone is not None:
        values["reporting_timezone"] = body.reportingTimezone
    if body.reportingCutoffTime is not None:
        values["reporting_cutoff_time"] = body.reportingCutoffTime
    if body.autoGenerateDpr is not None:
        values["auto_generate_dpr"] = body.autoGenerateDpr
    if body.dprSendDeadline is not None:
        values["dpr_send_deadline"] = _valid_send_deadline(body.dprSendDeadline)
    if body.requiredReportTypes is not None:
        values["required_report_types"] = body.requiredReportTypes

    if values:
        await conn.execute(_projects.update().where(_projects.c.id == project_id).values(**values))

    # Re-fetch
    refetch = await conn.execute(sa.select(_projects).where(_projects.c.id == project_id))
    row = refetch.first()

    from mesiri.application.projects.dtos import ProjectDTO

    dto = ProjectDTO(
        id=row.id,
        organization_id=row.organization_id,
        name=row.name,
        code=row.code,
        location=row.location,
        client=row.client,
        description=row.description,
        status=row.status or "on_track",
        progress=row.progress or 0,
        open_issues=row.open_issues or 0,
        reporting_timezone=row.reporting_timezone or "UTC",
        reporting_cutoff_time=row.reporting_cutoff_time or "18:00",
        auto_generate_dpr=bool(row.auto_generate_dpr),
        dpr_send_deadline=row.dpr_send_deadline or "21:00",
        required_report_types=row.required_report_types or None,
    )
    return ProjectPresenter.to_response(dto)


