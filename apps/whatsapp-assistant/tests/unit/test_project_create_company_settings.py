"""QA-2011 (20 Nov 2026): a project made from the dashboard in an Asia/Kolkata company, whose other project has
the daily report on, got UTC and no report ("Day closes at 6:00 pm" was 11:30 pm in India).

[259] (5 Nov) gave the backend's POST /projects the company's settings, but production serves this app's
projects router, which still took the column defaults. These tests hold the router production runs to the
same rule (application/projects/defaults.new_project_settings); the rule itself is tested in the backend
(test_new_project_settings_259.py)."""

from __future__ import annotations

import uuid
from types import SimpleNamespace
from typing import Any

import pytest
from fastapi import HTTPException

from projects import router as projects_router

ORG = str(uuid.uuid4())
ADMIN = {"org": ORG, "role": "ADMIN", "sub": str(uuid.uuid4())}


class Conn:
    """Answers the company's report project and zone, finds no project of the same name, keeps the insert."""

    def __init__(self, project: dict[str, Any] | None, zone: str | None) -> None:
        self.project, self.zone = project, zone
        self.inserted: dict[str, Any] = {}

    async def execute(self, statement: Any, params: Any = None) -> Any:  # noqa: ANN401
        if getattr(statement, "is_insert", False):
            self.inserted = dict(statement.compile().params)
            return SimpleNamespace()
        sql = str(statement)
        if "FROM organizations" in sql:
            return SimpleNamespace(scalar=lambda: self.zone)
        if "auto_generate_dpr DESC" in sql:
            return SimpleNamespace(mappings=lambda: SimpleNamespace(first=lambda: self.project))
        return SimpleNamespace(fetchall=lambda: [], first=lambda: None)


class Engine:
    def __init__(self, conn: Conn) -> None:
        self.conn = conn

    def begin(self) -> Any:  # noqa: ANN401
        conn = self.conn

        class _Ctx:
            async def __aenter__(self) -> Conn:
                return conn

            async def __aexit__(self, *exc: object) -> None:
                return None

        return _Ctx()


def _report_project(zone: str, on: bool) -> dict[str, Any]:
    return {"reporting_timezone": zone, "auto_generate_dpr": on, "reporting_cutoff_time": "18:00",
            "dpr_send_deadline": "21:00"}


@pytest.mark.asyncio
async def test_the_reported_case_takes_the_company_zone_and_report(monkeypatch: pytest.MonkeyPatch) -> None:
    # "cd": Asia/Kolkata; Green Villa has the report on. QA-2011 Sunrise Residency got UTC / off.
    conn = Conn(_report_project("Asia/Kolkata", True), "Asia/Kolkata")
    monkeypatch.setattr(projects_router, "get_engine", lambda: Engine(conn))
    made = await projects_router.create_project(projects_router.ProjectCreate(name="Sunrise Residency"), ADMIN)
    assert conn.inserted["reporting_timezone"] == "Asia/Kolkata" and conn.inserted["auto_generate_dpr"] is True
    assert made.reportingTimezone == "Asia/Kolkata" and made.autoGenerateDpr is True  # the reply says what is stored


@pytest.mark.asyncio
async def test_a_utc_project_beside_it_is_not_copied(monkeypatch: pytest.MonkeyPatch) -> None:
    # Sibling: the company's report project was itself left on UTC by the old default; the company zone wins.
    conn = Conn(_report_project("UTC", True), "Asia/Kolkata")
    monkeypatch.setattr(projects_router, "get_engine", lambda: Engine(conn))
    await projects_router.create_project(projects_router.ProjectCreate(name="Tower C"), ADMIN)
    assert conn.inserted["reporting_timezone"] == "Asia/Kolkata"


@pytest.mark.asyncio
async def test_what_the_caller_sends_still_wins(monkeypatch: pytest.MonkeyPatch) -> None:
    # Guard: the dashboard's Reporting settings and an explicit "no report" are kept.
    conn = Conn(_report_project("Asia/Kolkata", True), "Asia/Kolkata")
    monkeypatch.setattr(projects_router, "get_engine", lambda: Engine(conn))
    body = projects_router.ProjectCreate(name="Dubai Mall Fitout", reportingTimezone="Asia/Dubai",
                                         autoGenerateDpr=False, reportingCutoffTime="17:00")
    made = await projects_router.create_project(body, ADMIN)
    assert conn.inserted["reporting_timezone"] == "Asia/Dubai" and conn.inserted["auto_generate_dpr"] is False
    assert conn.inserted["reporting_cutoff_time"] == "17:00" and made.dprSendDeadline == "21:00"


# -- QA-04 step 2.1 and PS-05 on the router production serves ------------------------------------------------------

class SiteConn(Conn):
    """Also answers the project lookup and the project's sites."""

    def __init__(self, sites: list[str]) -> None:
        super().__init__(_report_project("Asia/Kolkata", True), "Asia/Kolkata")
        self.sites = sites

    async def execute(self, statement: Any, params: Any = None) -> Any:  # noqa: ANN401
        sql = str(statement)
        if "FROM sites" in sql and not getattr(statement, "is_insert", False):
            return SimpleNamespace(fetchall=lambda: [SimpleNamespace(id=uuid.uuid4(), name=n) for n in self.sites])
        if "FROM projects" in sql and "projects.id" in sql:
            return SimpleNamespace(first=lambda: SimpleNamespace(id=uuid.uuid4()))
        return await super().execute(statement, params)


@pytest.mark.asyncio
async def test_a_site_the_project_has_is_refused(monkeypatch: pytest.MonkeyPatch) -> None:
    conn = SiteConn(["Villa 1"])
    monkeypatch.setattr(projects_router, "get_engine", lambda: Engine(conn))
    with pytest.raises(HTTPException) as exc:
        await projects_router.create_project_site(uuid.uuid4(), projects_router.SiteCreate(name="villa 1"), ADMIN)
    assert exc.value.status_code == 409 and exc.value.detail == "Villa 1 is already a site of this project"
    assert conn.inserted == {}


@pytest.mark.asyncio
async def test_guard_a_new_site_is_added(monkeypatch: pytest.MonkeyPatch) -> None:
    conn = SiteConn(["Villa 1"])
    monkeypatch.setattr(projects_router, "get_engine", lambda: Engine(conn))
    made = await projects_router.create_project_site(uuid.uuid4(), projects_router.SiteCreate(name=" Villa 2 "), ADMIN)
    assert made.name == "Villa 2" and conn.inserted["name"] == "Villa 2"


@pytest.mark.asyncio
async def test_the_project_size_is_stored(monkeypatch: pytest.MonkeyPatch) -> None:
    conn = Conn(_report_project("Asia/Kolkata", True), "Asia/Kolkata")
    monkeypatch.setattr(projects_router, "get_engine", lambda: Engine(conn))
    body = projects_router.ProjectCreate(name="Palm Grove", projectType="villa", builtUpAreaSqft=12800, floors=2)
    made = await projects_router.create_project(body, ADMIN)
    assert conn.inserted["project_type"] == "villa" and conn.inserted["floors"] == 2
    assert made.projectType == "villa" and made.builtUpAreaSqft == 12800 and made.floors == 2
