"""BE-35: the live /projects API carries the reporting settings -- timezone,
cutoff, automatic DPR, send deadline, required report types. Before, it
ignored them, so the dashboard's Reporting tab saved nothing."""

from __future__ import annotations

import types
import uuid

import pytest
from fastapi import HTTPException

from projects.router import ProjectCreate, ProjectUpdate, _reporting_values, _to_response


def test_only_the_settings_sent_are_written_and_times_are_normalised():
    values = _reporting_values(
        ProjectUpdate(reportingCutoffTime="7:30", dprSendDeadline="21:00", autoGenerateDpr=True)
    )
    assert values == {
        "reporting_cutoff_time": "07:30",
        "dpr_send_deadline": "21:00",
        "auto_generate_dpr": True,
    }


def test_nothing_sent_writes_nothing():
    assert _reporting_values(ProjectUpdate(name="Renamed")) == {}


def test_switching_the_automatic_dpr_off_is_written():
    assert _reporting_values(ProjectUpdate(autoGenerateDpr=False)) == {"auto_generate_dpr": False}


def test_timezone_and_report_types_are_carried():
    values = _reporting_values(
        ProjectCreate(name="P", reportingTimezone="Asia/Kolkata", requiredReportTypes=["Workforce"])
    )
    assert values == {"reporting_timezone": "Asia/Kolkata", "required_report_types": ["Workforce"]}


@pytest.mark.parametrize(
    "body",
    [
        ProjectUpdate(reportingTimezone="Mars/Olympus"),
        ProjectUpdate(reportingCutoffTime="six pm"),
        ProjectUpdate(dprSendDeadline="25:00"),
    ],
)
def test_bad_values_are_refused(body):
    with pytest.raises(HTTPException) as exc:
        _reporting_values(body)
    assert exc.value.status_code == 400


def _row(**overrides):
    base = dict(
        id=uuid.uuid4(),
        name="Green Valley",
        location=None,
        code=None,
        client=None,
        description=None,
        status="on_track",
        progress=0,
        open_issues=0,
        client_logo_object_key=None,
        reporting_timezone="Asia/Kolkata",
        reporting_cutoff_time="19:00",
        auto_generate_dpr=True,
        dpr_send_deadline="21:30",
        required_report_types=["Workforce"],
    )
    base.update(overrides)
    return types.SimpleNamespace(**base)


def test_response_carries_the_settings():
    response = _to_response(_row())
    assert (
        response.reportingTimezone,
        response.reportingCutoffTime,
        response.autoGenerateDpr,
        response.dprSendDeadline,
        response.requiredReportTypes,
    ) == ("Asia/Kolkata", "19:00", True, "21:30", ["Workforce"])


def test_response_falls_back_to_the_column_defaults():
    response = _to_response(
        _row(
            reporting_timezone=None,
            reporting_cutoff_time=None,
            auto_generate_dpr=None,
            dpr_send_deadline=None,
            required_report_types=None,
        )
    )
    assert (
        response.reportingTimezone,
        response.reportingCutoffTime,
        response.autoGenerateDpr,
        response.dprSendDeadline,
        response.requiredReportTypes,
    ) == ("UTC", "18:00", False, "21:00", None)
