import * as React from 'react'
import { useQueryClient } from '@tanstack/react-query'
import { Input } from '@/components/ui/input'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select'
import { Label } from '@/components/ui/label'
import { Button } from '@/components/ui/button'
import { useToast } from '@/components/ui/toast-notification'
import { updateProject, type Project } from '@/lib/projects'
import { apiErrorMessage } from '@/lib/logo-upload'

// When this project's DPR is built and sent (WEB-08; flat form in WEB-28).
// "Required report types" is no longer offered: nothing reads it. The stored
// value is sent back untouched on save.

// DSH-03: IANA zones only (the server refuses anything else). India first, then
// the rest of the browser's list.
const FIRST_ZONES = ['Asia/Kolkata', 'Asia/Dubai', 'Asia/Singapore', 'Europe/London', 'UTC']
function allZones(): string[] {
  try {
    const rest = (Intl as unknown as { supportedValuesOf?: (key: string) => string[] }).supportedValuesOf?.('timeZone') ?? []
    return [...FIRST_ZONES, ...rest.filter((z) => !FIRST_ZONES.includes(z))]
  } catch {
    return FIRST_ZONES
  }
}
const TIMEZONES = allZones()
const isKnownZone = (z: string) => TIMEZONES.includes(z) || z === 'Asia/Calcutta'

/** "18:00:00" -> "18:00" for a time input. */
const hhmm = (t: string | null | undefined, fallback: string) => (t || fallback).slice(0, 5)

export function ProjectReportingTab({ project, readOnly = false }: { project: Project; readOnly?: boolean }) {
  const queryClient = useQueryClient()
  const toast = useToast()
  // A saved value that is not a real zone ("IST") is shown with a warning and
  // must be picked again; nothing is rewritten for them.
  const savedZone = project.reportingTimezone || 'Asia/Kolkata'
  const invalidSaved = !isKnownZone(savedZone)
  const [timezone, setTimezone] = React.useState(invalidSaved ? '' : savedZone)
  const [cutoffTime, setCutoffTime] = React.useState(hhmm(project.reportingCutoffTime, '18:00'))
  const [autoDpr, setAutoDpr] = React.useState(project.autoGenerateDpr || false)
  const [sendDeadline, setSendDeadline] = React.useState(hhmm(project.dprSendDeadline, '21:00'))
  const [saving, setSaving] = React.useState(false)

  const dirty =
    (timezone !== '' && timezone !== savedZone) ||
    cutoffTime !== hhmm(project.reportingCutoffTime, '18:00') ||
    autoDpr !== (project.autoGenerateDpr || false) ||
    sendDeadline !== hhmm(project.dprSendDeadline, '21:00')

  const save = async (e: React.FormEvent) => {
    e.preventDefault()
    if (!timezone) {
      toast.error('Pick a time zone', 'The saved time zone is not valid. Choose one from the list.')
      return
    }
    setSaving(true)
    try {
      await updateProject(project.id, {
        reportingTimezone: timezone,
        reportingCutoffTime: cutoffTime,
        autoGenerateDpr: autoDpr,
        dprSendDeadline: sendDeadline,
        requiredReportTypes: project.requiredReportTypes,
      })
      queryClient.invalidateQueries({ queryKey: ['project-details', project.id] })
      queryClient.invalidateQueries({ queryKey: ['projects-list'] })
      toast.success('Saved', 'The daily report times are updated.')
    } catch (err) {
      toast.error('Could not save', apiErrorMessage(err))
    } finally {
      setSaving(false)
    }
  }

  return (
    <form onSubmit={save} className="flex flex-col gap-4 text-sm">
      <div className="grid grid-cols-2 items-start gap-4 sm:grid-cols-3">
        <div className="grid gap-1.5">
          <Label htmlFor="repCutoff">Day closes at</Label>
          <Input id="repCutoff" type="time" value={cutoffTime} onChange={(e) => setCutoffTime(e.target.value)} disabled={readOnly} required className="h-9 dark:[color-scheme:dark]" />
          <p className="text-xs text-muted-foreground">Later updates count for the next day.</p>
        </div>
        <div className="grid gap-1.5">
          <Label htmlFor="repSendDeadline">Send the DPR by</Label>
          <Input id="repSendDeadline" type="time" value={sendDeadline} onChange={(e) => setSendDeadline(e.target.value)} disabled={readOnly} required className="h-9 dark:[color-scheme:dark]" />
        </div>
        <div className="col-span-2 grid gap-1.5 sm:col-span-1">
          <Label htmlFor="repTimezone">Time zone</Label>
          <Select value={timezone} onValueChange={setTimezone} disabled={readOnly}>
            <SelectTrigger id="repTimezone" className="h-9">
              <SelectValue placeholder="Pick a time zone" />
            </SelectTrigger>
            <SelectContent>
              {TIMEZONES.map((z) => (
                <SelectItem key={z} value={z}>
                  {z}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
          {invalidSaved && (
            <p className="text-xs text-destructive">
              "{savedZone}" is not a time zone, so reports use UTC. Pick the right one and save.
            </p>
          )}
        </div>
      </div>

      <label className="flex items-start gap-2.5">
        <input type="checkbox" checked={autoDpr} onChange={(e) => setAutoDpr(e.target.checked)} disabled={readOnly} className="mt-0.5 size-4 accent-primary" />
        <span>
          <span className="font-medium">Send the DPR automatically</span>
          <span className="block text-muted-foreground">
            {autoDpr
              ? 'It goes out as soon as every site is confirmed, or at the send time with unconfirmed sites shown as "Not reported".'
              : 'Off: nothing goes out by itself. Use Send now on the project DPR.'}
          </span>
        </span>
      </label>

      {!readOnly && (
        <div>
          <Button type="submit" size="sm" disabled={saving || !dirty} className="font-semibold">
            {saving ? 'Saving…' : 'Save'}
          </Button>
        </div>
      )}
    </form>
  )
}
